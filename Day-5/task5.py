import os
import fitz
import faiss
import numpy as np
from google.colab import files, userdata
from sentence_transformers import SentenceTransformer
from langchain_groq import ChatGroq
from langchain_text_splitters import RecursiveCharacterTextSplitter

groq_api_key = userdata.get("GROQ_API_KEY")

if not groq_api_key:
    raise ValueError("Add your Groq API key in Colab Secrets with the name 'groq_api_key'.")

os.environ["GROQ_API_KEY"] = groq_api_key

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0.2
)

uploaded = files.upload()

pdf_files = [name for name in uploaded if name.lower().endswith(".pdf")]

if not pdf_files:
    raise ValueError("Please upload a PDF file.")

pdf_path = pdf_files[0]
doc = fitz.open(pdf_path)

text = ""
for page in doc:
    text += page.get_text() + "\n"

if not text.strip():
    raise ValueError("No text found in the PDF. If it is a scanned PDF, OCR is required.")

print("PDF loaded successfully.")
print("Total characters:", len(text))

text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=1000,
    chunk_overlap=200
)

chunks = text_splitter.split_text(text)

if not chunks:
    raise ValueError("No text chunks were created.")

print("Total chunks:", len(chunks))

embedding_model = SentenceTransformer("all-MiniLM-L6-v2")

embeddings = embedding_model.encode(
    chunks,
    convert_to_numpy=True
).astype("float32")

dimension = embeddings.shape[1]

index = faiss.IndexFlatL2(dimension)
index.add(embeddings)

print("FAISS vector database created.")

def retrieve_context(question, top_k=3):
    question_embedding = embedding_model.encode(
        [question],
        convert_to_numpy=True
    ).astype("float32")

    distances, indices = index.search(question_embedding, min(top_k, len(chunks)))

    retrieved_chunks = [chunks[i] for i in indices[0] if i < len(chunks)]
    return "\n\n".join(retrieved_chunks)

def careerpilot_answer(question):
    context = retrieve_context(question)

    prompt = f"""
You are CareerPilot AI, a career and internship guidance assistant for college students.

Answer the user's question using the provided context.
If the answer is not available in the context, clearly say that the uploaded document does not contain that information.
Give simple, clear, and practical guidance.

Context:
{context}

Question:
{question}
"""

    response = llm.invoke(prompt)
    return response.content

question = "What skills should a college student develop to prepare for internships?"
print(careerpilot_answer(question))

while True:
    question = input("Ask CareerPilot AI (type 'exit' to stop): ")

    if question.strip().lower() == "exit":
        print("Thank you for using CareerPilot AI!")
        break

    if not question.strip():
        print("Please enter a question.")
        continue

    answer = careerpilot_answer(question)
    print("\nCareerPilot AI:", answer)
    print("\n" + "-" * 60 + "\n")