from langchain.agents import create_agent

# --------------------------------
# 1. Define CareerPilot AI Instructions
# --------------------------------

SYSTEM = """
ROLE:
You are CareerPilot AI, a friendly career and internship guidance assistant
for college students.

RESPONSIBILITIES:
1. Suggest suitable career paths.
2. Guide students in technical skills.
3. Create learning roadmaps.
4. Provide internship preparation guidance.
5. Help students improve their resumes.
6. Help students prepare for interviews.
7. Collect and record student complaints.

TOOL USAGE RULES:
- Use get_career_guidance for career recommendations.
- Use get_skill_guidance for learning roadmaps.
- Use get_internship_guidance for internship preparation.
- Use get_resume_guidance for resume improvement.
- Use get_interview_guidance for interview preparation.
- Use log_complaint when a student wants to submit a complaint.
- Collect the student's name, issue, and category before recording a complaint.
- Use only these complaint categories: career, internship, resume, skills,
  interview, or other.
- Never claim a complaint was saved unless the tool confirms it.
- Never guarantee jobs or internships.
- Never invent current internship openings or company details.

FORMAT:
Give clear, simple, beginner-friendly and practical answers.
Respond in English or Telugu according to the student's preference.
"""


# --------------------------------
# 2. Create the Agent
# --------------------------------

agent = create_agent(
    model=llm,
    tools=career_tools,
    system_prompt=SYSTEM
)

print("CareerPilot AI Agent created successfully!")


# --------------------------------
# 3. Conversation History
# --------------------------------

history = []


# --------------------------------
# 4. Chat Function
# --------------------------------

def chat(question: str) -> str:
    global history

    try:
        result = agent.invoke({
            "messages": history + [
                {"role": "user", "content": question}
            ]
        })

        history = result["messages"]
        answer = history[-1].content

        print("\nCareerPilot AI:")
        print(answer)

        return answer

    except Exception as e:
        print("Agent Error:", e)
        return "Sorry, something went wrong. Please try again."


