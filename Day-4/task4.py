from langchain_core.tools import tool

# --------------------------------
# 1. Career Guidance Tool
# --------------------------------

@tool
def get_career_guidance(interest: str) -> str:
    """Suggest career paths and required skills based on a student's interest."""

    interest = interest.lower().strip()

    if interest in CAREERS:
        details = CAREERS[interest]
        return (
            f"Career: {interest.title()}\\n"
            f"Required Skills: {', '.join(details['skills'])}\\n"
            f"Advice: {details['advice']}"
        )

    return (
        f"No fixed career profile is available for {interest}. "
        "Suggest suitable career paths based on the student's interests "
        "and explain the skills required."
    )


# --------------------------------
# 2. Skill Guidance Tool
# --------------------------------

@tool
def get_skill_guidance(domain: str, level: str = "beginner") -> str:
    """Suggest technical skills and a learning roadmap for a career domain."""

    domain = domain.lower().strip()

    if domain in CAREERS:
        skills = CAREERS[domain]["skills"]
        return (
            f"Learning Roadmap for {domain.title()}\\n"
            f"Current Level: {level}\\n"
            f"Skills to Learn: {', '.join(skills)}\\n"
            "Start with fundamentals, practise regularly, and build small projects."
        )

    return (
        f"Create a beginner-friendly learning roadmap for {domain}. "
        f"The student's current level is {level}."
    )


# --------------------------------
# 3. Internship Guidance Tool
# --------------------------------

@tool
def get_internship_guidance(domain: str) -> str:
    """Explain how to prepare and apply for internships in a selected domain."""

    return (
        f"Internship preparation for {domain}:\\n"
        "1. Learn the required technical skills.\\n"
        "2. Build relevant projects.\\n"
        "3. Prepare a clear resume.\\n"
        "4. Search company career pages and trusted internship portals.\\n"
        "5. Practise technical and HR interviews.\\n"
        "Verify internship details before applying. This tool does not check live openings."
    )


# --------------------------------
# 4. Resume Guidance Tool
# --------------------------------

@tool
def get_resume_guidance(resume_details: str) -> str:
    """Review the resume details provided by a student and suggest improvements."""

    return (
        f"Resume Details:\\n{resume_details}\\n\\n"
        "Review the resume based on education, technical skills, projects, "
        "certifications, achievements, and formatting. "
        "Suggest practical improvements without inventing qualifications."
    )


# --------------------------------
# 5. Interview Guidance Tool
# --------------------------------

@tool
def get_interview_guidance(role: str) -> str:
    """Provide interview preparation topics and questions for a job role."""

    return (
        f"Interview preparation for {role}:\\n"
        "1. Basic technical questions.\\n"
        "2. Programming questions.\\n"
        "3. HR interview questions.\\n"
        "4. Sample answers and explanations.\\n"
        "5. Interview preparation tips."
    )


# --------------------------------
# 6. Student Complaint Logging Tool
# --------------------------------

@tool
def log_complaint(name: str, issue: str, category: str) -> str:
    """Validate and save a student's career or internship complaint to Google Sheets."""

    try:
        complaint = StudentComplaint(
            name=name,
            issue=issue,
            category=category.lower().strip()
        )

        ws.append_row([
            complaint.name,
            complaint.issue,
            complaint.category,
            complaint.status
        ])

        return "Student complaint saved successfully to Google Sheets!"

    except Exception as e:
        return f"Could not save complaint: {str(e)}"


