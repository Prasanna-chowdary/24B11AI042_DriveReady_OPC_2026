class StudentComplaint(BaseModel):
    name: str = Field(description="Student's name")
    issue: str = Field(description="Student's career or internship issue")

    category: Literal[
        "career",
        "internship",
        "resume",
        "skills",
        "interview",
        "other"
    ]

    status: Literal["pending", "resolved"] = "pending"


